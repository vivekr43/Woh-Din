export function getQuoteForDate(date: Date): DayQuote {
  const day = date.getDate();
  const month = date.getMonth() + 1;
  const year = date.getFullYear();
  // High-dispersion hash formula so every calendar date gets a unique quote
  const hash = Math.abs((year * 367 + month * 79 + day * 31) % FAMOUS_QUOTES.length);
  return FAMOUS_QUOTES[hash];
}
